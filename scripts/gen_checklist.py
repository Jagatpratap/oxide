#!/usr/bin/env python3
"""Generate docs/UNITY_FEATURE_CHECKLIST.md from the Unity Manual table of contents.

Usage: python3 scripts/gen_checklist.py docs/reference/unity_manual_toc.json docs/UNITY_FEATURE_CHECKLIST.md
Refresh the TOC with: curl -sL https://docs.unity3d.com/Manual/docdata/toc.json -o docs/reference/unity_manual_toc.json
"""
import json
import sys

BASE = "https://docs.unity3d.com/Manual/"

# Top-level Unity manual section -> Oxide roadmap phase (see docs/ROADMAP.md).
PHASE = {
    "Get started": "P1",
    "GameObjects": "P1",
    "Scenes": "P1",
    "Unity Editor interface": "P2",
    "Assets and media": "P3",
    "Render pipelines": "P4",
    "Cameras": "P4",
    "Materials and shaders": "P4",
    "Lighting": "P5",
    "Post-processing": "P5",
    "Gameplay programming": "P6",
    "Unity programming environment": "P6",
    "Physics": "P7",
    "Input": "P7",
    "2D game development": "P7",
    "Animation": "P8",
    "Audio": "P8",
    "Video and cutscenes": "P8",
    "UI systems": "P8",
    "Accessibility": "P8",
    "World building": "P8",
    "Visual effects": "P8",
    "Packages and package management": "P9",
    "Extending the Unity Editor": "P9",
    "Optimization": "P9",
    "Building and publishing": "P10",
    "Platform development": "P10",
    "XR": "P11",
    "Multiplayer": "P11",
}
SKIP = {"Unity 6.6 User Manual", "What's new in Unity", "Upgrade Unity", "Unity Building Blocks",
        "Unity's AI", "Unity Services", "Best practice guides", "Troubleshooting", "Glossary"}


def count(node):
    return 1 + sum(count(c) for c in node.get("children") or [])


def emit(node, depth, out):
    title = node["title"].strip()
    link = node.get("link")
    label = f"[{title}]({BASE}{link}.html)" if link else title
    out.append(f"{'  ' * depth}- [ ] {label}")
    for child in node.get("children") or []:
        emit(child, depth + 1, out)


def main(toc_path, out_path):
    toc = json.load(open(toc_path))
    sections = [s for s in toc["children"] if s["title"].strip() not in SKIP]
    skipped = [s["title"].strip() for s in toc["children"] if s["title"].strip() in SKIP]
    total = sum(count(s) for s in sections)

    out = [
        "# Unity Manual → Oxide Feature Checklist",
        "",
        "Auto-generated by `scripts/gen_checklist.py` from the Unity Manual table of contents",
        f"({BASE}docdata/toc.json). Do not hand-edit the structure; tick boxes as features land.",
        "",
        f"**{len(sections)} sections, {total} manual pages tracked.** Phase IDs refer to `docs/ROADMAP.md`.",
        "",
        "Not tracked (release notes, Unity cloud services, upgrade guides): " + ", ".join(skipped) + ".",
        "",
        "## Index",
        "",
        "| Section | Phase | Pages |",
        "|---|---|---|",
    ]
    for s in sections:
        t = s["title"].strip()
        anchor = "".join(ch for ch in t.lower().replace(" ", "-") if ch.isalnum() or ch == "-")
        out.append(f"| [{t}](#{anchor}) | {PHASE.get(t, '—')} | {count(s)} |")
    for s in sections:
        t = s["title"].strip()
        out += ["", f"## {t}", "", f"Phase **{PHASE.get(t, '—')}** · Unity docs: {BASE}{s['link']}.html", ""]
        for child in s.get("children") or []:
            emit(child, 0, out)
    open(out_path, "w").write("\n".join(out) + "\n")
    print(f"wrote {out_path}: {len(sections)} sections, {total} pages")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
